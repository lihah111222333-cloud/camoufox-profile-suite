let dockStackPinnedOnce = false;

export async function ensureDockFanStackPinned() {
    if (process.platform !== 'darwin') return false;
    if (dockStackPinnedOnce) return true;
    const dir = fs.realpathSync(getActiveDockStackDir());
    for (const py of ['/opt/homebrew/bin/python3', '/usr/bin/python3', 'python3']) {
        try {
            await execFileAsync(py, ['-c', PIN_DOCK_STACK_PY, dir], { timeout: 8000 });
            dockStackPinnedOnce = true;
            return true;
        } catch {
            // try next python
        }
    }
    return false;
}

/**
 * Launch the native macOS non-activating floating 2FA & One-Click Autofill HUD
 * bound to a specific browser PID. Automatically hides when another app/window is
 * frontmost and exits automatically when the browser closes.
 */
export function spawnBrowserAccountHud({ profile, pid, runtimeRoot }) {
    if (process.platform !== 'darwin' || !pid || !profile) return null;
    const email = String(profile.account_email || '').trim();
    const password = String(profile.account_password || '');
    const totp = String(profile.account_totp || '').trim();
    if (!email && !password && !totp) return null;

    const hudScript = path.join(__brandingDir, 'browser-hud.py');
    if (!fs.existsSync(hudScript)) return null;

    const pyBin = fs.existsSync('/opt/homebrew/bin/python3')
        ? '/opt/homebrew/bin/python3'
        : '/usr/bin/python3';

    const payloadPath = path.join(runtimeRoot, `.hud-${pid}-${Date.now()}.json`);
    const payload = {
        pid: Number(pid),
        serial: profile.serial_number != null ? String(profile.serial_number) : '•',
        email,
        password,
        totp
    };
    writePrivateFile(payloadPath, JSON.stringify(payload), { requireOwner: true });

    const child = spawn(pyBin, [hudScript, payloadPath], {
        detached: false,
        stdio: 'ignore'
    });
    child.on('error', () => {});

    return {
        pid: child.pid,
        close: () => {
            try {
                if (!child.killed && child.exitCode === null) child.kill('SIGTERM');
            } catch {
                // ignore
            }
            try {
                if (fs.existsSync(payloadPath)) fs.unlinkSync(payloadPath);
            } catch {
                // ignore
            }
        }
    };
}
