/**
 * Returns a directory OUTSIDE `$HOME` on the INTERNAL macOS APFS boot volume
 * (`/Users/Shared/CamoufoxStudio/apps/<id>`) for storing the APFS copy-on-write
 * `Browser-<serial>.app` wrapper.
 *
 * Why `/Users/Shared/CamoufoxStudio/apps/<id>` instead of `~/Library/Caches/...`?
 * 1. Same APFS volume (`/System/Volumes/Data`) as `/Applications/Firefox.app` ->
 *    `cp -cR` takes ~15ms and uses 0 extra disk bytes (copy-on-write).
 * 2. Internal boot drive (not `/Volumes/...`) -> zero macOS removable-volume TCC prompts.
 * 3. OUTSIDE `$HOME` -> Firefox's macOS Seatbelt `ContentSandboxLevel=3` policy denies
 *    reading under `$HOME` after `(allow file-read* (subpath appPath))`, which caused
 *    `Omnijar::Init failed: NS_ERROR_FILE_CORRUPTED` tab crashes when `.app` lived under `~/`.
 */
export function getInternalAppWrapperRoot(profileId, fallbackDir) {
    const safeId = String(profileId || 'default').replace(/[^a-zA-Z0-9._-]/g, '_');
    if (process.platform === 'darwin') {
        const base = '/Users/Shared/CamoufoxStudio';
        const appsDir = path.join(base, 'apps');
        const dir = path.join(appsDir, safeId);
        fs.mkdirSync(dir, { recursive: true, mode: 0o755 });
        return dir;
    }
    return fallbackDir;
}

