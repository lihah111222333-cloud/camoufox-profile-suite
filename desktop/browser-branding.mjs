/**
 * Returns a private directory on the INTERNAL macOS boot volume (`~/Library/Caches/CamoufoxStudio/profiles/<id>`)
 * so per-profile numbered `.app` wrappers & Firefox `browser-data` NEVER touch removable volumes (`/Volumes/...`)
 * and therefore NEVER trigger macOS TCC "access files on a removable volume" prompts!
 */
export function getInternalProfileRuntimeRoot(profileId, fallbackProfileRoot) {
    const safeId = String(profileId || 'default').replace(/[^a-zA-Z0-9._-]/g, '_');
    if (process.platform === 'darwin') {
        const base = path.join(os.homedir(), 'Library', 'Caches', 'CamoufoxStudio', 'profiles');
        ensurePrivateDirectory(path.join(os.homedir(), 'Library', 'Caches', 'CamoufoxStudio'), { requireOwner: true });
        ensurePrivateDirectory(base, { requireOwner: true });
        const dir = path.join(base, safeId);
        ensurePrivateDirectory(dir, { requireOwner: true });
        return dir;
    }
    ensurePrivateDirectory(fallbackProfileRoot, { requireOwner: true });
    return fallbackProfileRoot;
}

function escapeHtml(value) {
    return String(value ?? '')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

function escapeCssContent(value) {
    return String(value ?? '')
        .replace(/\\/g, '\\\\')
        .replace(/"/g, '\\"')
        .replace(/[\r\n]/g, ' ');
}

export function formatProfileBadgeLabel(profile) {
    const num = profile?.serial_number ? `#${profile.serial_number}` : '';
    const acct = String(profile?.account_email || '').trim();
    const name = String(profile?.name || '').trim();
    const primary = acct || name || profile?.id || 'Profile';
    return num ? `${num} · ${primary}` : primary;
}

